#!/bin/bash
# Write build/engine.xcconfig from pkg-config so the XcodeGen project
# (project.yml) compiles and links against the same engine as
# scripts/build-bridge.sh.  Re-run after scripts/build-gnumeric.sh or any brew
# upgrade; project.yml's configFiles point at the output.
#   scripts/gen-xcconfig.sh
set -euo pipefail
cd "$(dirname "$0")/.."
# shellcheck source=env.sh
source scripts/env.sh
PKGS="libspreadsheet-1.12 cairo-quartz"
mkdir -p build

# -I dirs become HEADER_SEARCH_PATHS, -L dirs LIBRARY_SEARCH_PATHS; everything
# else stays as flags.  Xcode wants paths space-separated and unquoted (none
# of ours contain spaces).
includes=$(pkg-config --cflags-only-I $PKGS | tr ' ' '\n' | sed -n 's/^-I//p' | tr '\n' ' ')
cflags=$(pkg-config --cflags-only-other $PKGS)
libdirs=$(pkg-config --libs-only-L $PKGS | tr ' ' '\n' | sed -n 's/^-L//p' | tr '\n' ' ')
ldflags=$(pkg-config --libs-only-l --libs-only-other $PKGS | sed 's/-Wl,-framework,/-framework /g')

cat > build/engine.xcconfig <<XC
// Generated by scripts/gen-xcconfig.sh on $(date +%Y-%m-%d); do not edit.
// Engine: libspreadsheet $(pkg-config --modversion libspreadsheet-1.12) from $(pkg-config --variable=prefix libspreadsheet-1.12)
GNM_PREFIX = $(pkg-config --variable=prefix libspreadsheet-1.12)
GNM_HEADER_SEARCH_PATHS = $includes
GNM_OTHER_CFLAGS = $cflags -Wno-deprecated-declarations
GNM_LIBRARY_SEARCH_PATHS = $libdirs
GNM_OTHER_LDFLAGS = $ldflags
XC
echo "wrote build/engine.xcconfig for libspreadsheet $(pkg-config --modversion libspreadsheet-1.12)"

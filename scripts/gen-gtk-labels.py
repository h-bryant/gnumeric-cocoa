#!/usr/bin/env python3
"""Write Sources/App/GTKLabels.swift: the GTK's action labels (the message
ids in the gnumeric catalog, with their mnemonic underscores and "...")
keyed by the plain title the app uses, from
upstream/gnumeric/src/wbc-gtk-actions.c.  Localization.title looks a menu
title up here and asks the engine's catalog for its translation.
    scripts/gen-gtk-labels.py
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
source = os.path.join(root, "upstream/gnumeric/src/wbc-gtk-actions.c")
target = os.path.join(root, "Sources/App/GTKLabels.swift")

def unescape(text):
    """A C string literal's contents as the UTF-8 text it encodes
    ("Display _Formul\\303\\246" is "Display _Formulæ")."""
    out = bytearray()
    i = 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            n = text[i + 1]
            m = re.match(r"[0-7]{1,3}", text[i + 1:])
            if m:
                out.append(int(m.group(0), 8))
                i += 1 + len(m.group(0))
                continue
            out.extend({"n": b"\n", "t": b"\t", '"': b'"', "\\": b"\\"}.get(n, n.encode()))
            i += 2
            continue
        out.extend(c.encode("utf-8"))
        i += 1
    return out.decode("utf-8")

def plain(label):
    """The title without its mnemonic ("__" is a literal underscore) and
    with "..." as an ellipsis, as the app writes titles."""
    label = label.replace("__", "\0").replace("_", "").replace("\0", "_")
    return label.replace("...", "…").strip()

with open(source, "rb") as f:
    text = f.read().decode("utf-8", errors="replace")
labels = [unescape(l) for l in re.findall(r'\.label\s*=\s*N_\s*\("((?:[^"\\]|\\.)*)"\)', text)]
table = {}
for label in labels:
    table.setdefault(plain(label), label)

def swift(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

lines = ["// Generated by scripts/gen-gtk-labels.py from",
         "// upstream/gnumeric/src/wbc-gtk-actions.c; do not edit.",
         "//",
         "// The GTK's action labels, the message ids in the gnumeric catalog (with",
         "// their mnemonic underscores and \"...\"), by the plain title the app's",
         "// menus use.  Localization.title looks a title up here and asks the",
         "// engine's catalog for its translation.",
         "enum GTKLabels {",
         "    static let messages: [String: String] = ["]
for key in sorted(table):
    lines.append(f"        {swift(key)}: {swift(table[key])},")
lines += ["    ]", "}", ""]
with open(target, "w") as f:
    f.write("\n".join(lines))
print(f"{len(table)} labels from {len(labels)} in {os.path.relpath(target, root)}")

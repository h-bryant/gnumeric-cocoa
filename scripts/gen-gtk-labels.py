#!/usr/bin/env python3
"""Write Sources/App/GTKLabels.swift: the GTK's action labels (the message
ids in the gnumeric catalog, with their mnemonic underscores and "...")
keyed by the plain title the app uses, from
upstream/gnumeric/src/wbc-gtk-actions.c; and the loose matches, the
app's own strings (every literal the Swift sources pass to
Localization.title or to the dialog helpers) that equal a catalog
message apart from case, a trailing colon, an ellipsis, or spacing
("Predicted mean:" is the GTK's "_Predicted Mean:").  The catalog's
message ids come from po/de.po, which every language's file shares.
Localization.title looks a title up in both tables and asks the engine's
catalog for its translation.
    scripts/gen-gtk-labels.py
"""
import glob, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
source = os.path.join(root, "upstream/gnumeric/src/wbc-gtk-actions.c")
catalog = os.path.join(root, "upstream/gnumeric/po/de.po")
target = os.path.join(root, "Sources/App/GTKLabels.swift")

def unescape(text):
    """A C string literal's contents as the UTF-8 text it encodes
    ("Display _Formul\\303\\246" is "Display _Formulæ")."""
    out = bytearray()
    i = 0
    while i < len(text):
        c = text[i]
        if c == "\\" and i + 1 < len(text):
            n = text[i + 1]
            m = re.match(r"[0-7]{1,3}", text[i + 1:])
            if m:
                out.append(int(m.group(0), 8))
                i += 1 + len(m.group(0))
                continue
            out.extend({"n": b"\n", "t": b"\t", '"': b'"', "\\": b"\\"}.get(n, n.encode()))
            i += 2
            continue
        out.extend(c.encode("utf-8"))
        i += 1
    return out.decode("utf-8")

def plain(label):
    """The title without its mnemonic ("__" is a literal underscore) and
    with "..." as an ellipsis, as the app writes titles."""
    label = label.replace("__", "\0").replace("_", "").replace("\0", "_")
    return label.replace("...", "…").strip()

with open(source, "rb") as f:
    text = f.read().decode("utf-8", errors="replace")
labels = [unescape(l) for l in re.findall(r'\.label\s*=\s*N_\s*\("((?:[^"\\]|\\.)*)"\)', text)]
table = {}
for label in labels:
    table.setdefault(plain(label), label)

def swift(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

# The catalog's message ids, by a loose key.
def loose(s):
    s = plain(s).lower().strip()
    s = re.sub(r"[\s]+", " ", s)
    return s.rstrip("…:. ").strip()

with open(catalog, "rb") as f:
    po = f.read().decode("utf-8", errors="replace")
messages = {}
for raw in re.findall(r'^msgid "((?:[^"\\]|\\.)*)"$', po, re.M):
    m = unescape(raw)
    if not m or "<" in m or "%" in m or "\n" in m:
        continue
    messages.setdefault(loose(m), m)

# The app's strings: what the Swift sources pass to Localization.title
# (L in MainMenu), the dialog helpers, and the pop-up entry lists.
ours = set()
for path in glob.glob(os.path.join(root, "Sources/App/*.swift")):
    if os.path.basename(path) in ("GTKLabels.swift",):
        continue
    with open(path) as f:
        text = f.read()
    ours.update(re.findall(r'\b(?:Localization\.title|L|label|heading|sectionLabel)\("([^"\\]+)"\)', text))
    ours.update(re.findall(r'\brow\("([^"\\]+)",', text))
    for group in re.findall(r"addItems\(withTitles: \[([^\]]*)\]", text):
        ours.update(x.strip().strip('"') for x in group.split(",") if x.strip().startswith('"'))
ours = {s for s in ours if s.strip()}

def exact(s):
    """The variants Localization.title tries itself."""
    bare = s[:-1] if s.endswith(":") else s
    dotted = bare.replace("…", "...")
    forms = [dotted, "_" + dotted]
    if s.endswith(":"):
        forms = [dotted + ":", "_" + dotted + ":"] + forms
    if dotted.endswith("..."):
        forms += [dotted[:-3], "_" + dotted[:-3]]
    return forms

all_ids = set(messages.values()) | {unescape(r) for r in re.findall(r'^msgid "((?:[^"\\]|\\.)*)"$', po, re.M)}
loose_matches = {}
for s in sorted(ours):
    if s in table or any(form in all_ids for form in exact(s)):
        continue
    key = loose(s)
    if key and key in messages and messages[key] != s:
        loose_matches[s] = messages[key]

lines = ["// Generated by scripts/gen-gtk-labels.py from",
         "// upstream/gnumeric/src/wbc-gtk-actions.c; do not edit.",
         "//",
         "// The GTK's action labels, the message ids in the gnumeric catalog (with",
         "// their mnemonic underscores and \"...\"), by the plain title the app's",
         "// menus use.  Localization.title looks a title up here and asks the",
         "// engine's catalog for its translation.",
         "enum GTKLabels {",
         "    static let messages: [String: String] = ["]
for key in sorted(table):
    lines.append(f"        {swift(key)}: {swift(table[key])},")
lines += ["    ]", "",
          "    /// The app's strings that are a catalog message apart from case, a",
          "    /// trailing colon, an ellipsis, or spacing, by the string as written.",
          "    static let looseMatches: [String: String] = ["]
for key in sorted(loose_matches):
    lines.append(f"        {swift(key)}: {swift(loose_matches[key])},")
lines += ["    ]", "}", ""]
with open(target, "w") as f:
    f.write("\n".join(lines))
print(f"{len(table)} labels from {len(labels)}, {len(loose_matches)} loose matches of {len(ours)} app strings, in {os.path.relpath(target, root)}")

        editMenu.addItem(withTitle: "Paste Special…", action: Selector(("pasteSpecial:")), keyEquivalent: "V")
        editMenu.addItem(withTitle: "Delete", action: #selector(NSText.delete(_:)), keyEquivalent: "")
        let clearMenu = NSMenu(title: "Clear")

        statisticsMenu.addItem(.separator())
        statisticsMenu.addItem(withTitle: "Regression…", action: Selector(("regression:")), keyEquivalent: "")
        statisticsMenu.addItem(withTitle: "Two Means…", action: Selector(("meanTest:")), keyEquivalent: "")
        statisticsMenu.addItem(withTitle: "Two Variances…", action: Selector(("varianceTest:")), keyEquivalent: "")

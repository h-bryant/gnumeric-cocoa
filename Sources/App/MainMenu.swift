        let viewMenu = NSMenu(title: "View")
        let zoomIn = viewMenu.addItem(withTitle: "Zoom In", action: Selector(("zoomIn:")), keyEquivalent: "+")
        zoomIn.keyEquivalentModifierMask = [.command]

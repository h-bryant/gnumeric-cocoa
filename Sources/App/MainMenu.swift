        statisticsMenu.addItem(withTitle: "Descriptive Statistics…", action: Selector(("descriptiveStatistics:")), keyEquivalent: "")
        statisticsMenu.addItem(withTitle: "Correlation…", action: Selector(("correlation:")), keyEquivalent: "")
